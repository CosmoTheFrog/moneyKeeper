import { describe, expect, it } from 'vitest'
import { pressKey } from './amountKeys'

describe('pressKey', () => {
  it.each([
    ['', '5', 2, '5'],
    ['5', '0', 2, '50'],
    ['0', '7', 2, '7'],
    ['0', '0', 2, '0'],
    ['', ',', 2, '0,'],
    ['12', ',', 2, '12,'],
    ['12,5', ',', 2, '12,5'],
    ['12.5', ',', 2, '12.5'],
    ['12,5', '0', 2, '12,50'],
    ['12,50', '1', 2, '12,50'],
    ['12', ',', 0, '12'],
    ['0,00000001', '1', 8, '0,00000001'],
    ['0,0000000', '1', 8, '0,00000001'],
    ['12345678901234', '1', 2, '12345678901234'],
    ['12,5', 'back', 2, '12,'],
    ['', 'back', 2, ''],
    ['5', 'x', 2, '5'],
  ])('%j + %j (%i digits) -> %j', (value, key, units, want) => {
    expect(pressKey(value, key, units)).toBe(want)
  })
})
